/// Generates version and schema identity from the current Rust contract.
pub fn protocol_metadata() -> String {
    let metadata = serde_json::json!({
        "major": crate::protocol::initialize::APP_SERVER_PROTOCOL_MAJOR,
        "revision": crate::protocol::initialize::APP_SERVER_PROTOCOL_REVISION,
        "schemaHash": schema_hash(),
    });
    let mut output =
        serde_json::to_string_pretty(&metadata).expect("protocol metadata must serialize as JSON");
    output.push('\n');
    output
}

/// Prefix that identifies TypeScript files owned by the protocol generator.
pub const GENERATED_TYPESCRIPT_HEADER: &str =
    "// Generated by `ash-app-server-protocol generate_protocol`. Do not edit.\n";

#[allow(dead_code)]
#[derive(JsonSchema)]
#[schemars(title = "Ash App Server Protocol")]
#[serde(rename_all = "camelCase")]
struct ProtocolSchema {
    listen_info: AppServerListenInfo,
    web_listen_info: crate::WebListenInfo,
    web_session_info: crate::WebSessionInfo,
    client_request: JsonRpcRequest<ClientRequestSchema>,
    client_response: JsonRpcResponse<ClientResultSchema, AppServerError>,
    host_request: JsonRpcRequest<HostRequestSchema>,
    host_response: JsonRpcResponse<HostResultSchema, JsonRpcError>,
    server_notification: JsonRpcNotification<ServerNotificationSchema>,
    error_response: JsonRpcFailure<AppServerError>,
}

fn generated_protocol() -> String {
    assert_typescript_bindings_are_closed();
    let schema_hash = schema_hash();
    format!(
        "{GENERATED_TYPESCRIPT_HEADER}\
         export const APP_SERVER_PROTOCOL_MAJOR = {} as const;\n\
         export const APP_SERVER_PROTOCOL_REVISION = {} as const;\n\
         export const APP_SERVER_CAPABILITY_VERSION = {} as const;\n\
         export const APP_SERVER_SCHEMA_HASH = {schema_hash:?} as const;\n\
         export type JsonRpcVersion = \"2.0\";\n\
         export type JsonRpcId = number | string | null;\n\
         export type JsonRpcRequest<P> = {{ jsonrpc: JsonRpcVersion; id: JsonRpcId; method: string; params: P }};\n\
         export type JsonRpcNotification<P> = {{ jsonrpc: JsonRpcVersion; method: string; params: P }};\n\
         export type JsonRpcSuccess<R> = {{ jsonrpc: JsonRpcVersion; id: JsonRpcId; result: R }};\n\
         export type JsonRpcFailure<E> = {{ jsonrpc: JsonRpcVersion; id: JsonRpcId; error: E }};\n\
         export type JsonRpcResponse<R, E> = JsonRpcSuccess<R> | JsonRpcFailure<E>;\n\
         export type JsonRpcError = {{ code: number; message: string; data: unknown }};\n",
        crate::protocol::initialize::APP_SERVER_PROTOCOL_MAJOR,
        crate::protocol::initialize::APP_SERVER_PROTOCOL_REVISION,
        crate::protocol::initialize::APP_SERVER_CAPABILITY_VERSION,
    )
}

fn generated_request_map() -> String {
    let mut type_expressions = vec!["AppServerError".to_owned()];
    for method in CLIENT_METHODS {
        type_expressions.push(method.params_type());
        type_expressions.push(method.result_type());
    }

    let mut output = String::from(GENERATED_TYPESCRIPT_HEADER);
    output.push_str(&generated_type_imports(type_expressions));
    output.push_str("import type { JsonRpcRequest, JsonRpcResponse } from './protocol.js';\n\n");

    output.push_str("export interface AppServerRequestMap {\n");
    for method in CLIENT_METHODS {
        output.push_str(&format!(
            "  {:?}: {{ params: {}; response: {} }};\n",
            method.method,
            method.params_type(),
            method.result_type()
        ));
    }
    output.push_str(
        "}\n\
         export type AppServerMethod = keyof AppServerRequestMap;\n\
         export type MethodParams<M extends AppServerMethod> = AppServerRequestMap[M][\"params\"];\n\
         export type MethodResult<M extends AppServerMethod> = AppServerRequestMap[M][\"response\"];\n\
         export type AppServerRequest<M extends AppServerMethod> = JsonRpcRequest<MethodParams<M>> & { method: M };\n\
         export type AppServerResponse<M extends AppServerMethod> = JsonRpcResponse<MethodResult<M>, AppServerError>;\n\
         export type AppServerMethodDefinition<M extends AppServerMethod> = {\n\
           readonly method: M;\n\
           readonly __params?: MethodParams<M>;\n\
           readonly __result?: MethodResult<M>;\n\
         };\n\
         export const APP_SERVER_METHODS: { [M in AppServerMethod]: AppServerMethodDefinition<M> } = {\n",
    );
    for method in CLIENT_METHODS {
        output.push_str(&format!(
            "  {:?}: {{ method: {:?} }},\n",
            method.method, method.method
        ));
    }
    output.push_str("};\n");
    output
}


fn generated_types_index() -> String {
    let mut bindings = TYPESCRIPT_BINDINGS.iter().collect::<Vec<_>>();
    bindings.sort_by_key(|binding| binding.identifier());
    let mut output = String::from(GENERATED_TYPESCRIPT_HEADER);
    for binding in bindings {
        output.push_str(&format!(
            "export type {{ {} }} from '{}';\n",
            binding.identifier(),
            typescript_module_path("./", &binding_output_path(binding))
        ));
    }
    output
}


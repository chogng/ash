fn generated_type_imports(type_expressions: Vec<String>) -> String {
    let identifiers = registered_type_identifiers(&type_expressions);
    let mut imports = BTreeMap::new();
    for binding in TYPESCRIPT_BINDINGS {
        let identifier = binding.identifier();
        if identifiers.contains(&identifier) {
            imports.insert(binding_output_path(binding), identifier);
        }
    }

    let mut output = String::new();
    for (path, identifier) in imports {
        output.push_str(&format!(
            "import type {{ {identifier} }} from '{}';\n",
            typescript_module_path("./types/", &path)
        ));
    }
    output
}

fn registered_type_identifiers(type_expressions: &[String]) -> BTreeSet<String> {
    let identifiers = type_expressions
        .iter()
        .flat_map(|expression| {
            expression
                .split(|character: char| !character.is_ascii_alphanumeric() && character != '_')
        })
        .collect::<BTreeSet<_>>();
    TYPESCRIPT_BINDINGS
        .iter()
        .map(|binding| binding.identifier())
        .filter(|identifier| identifiers.contains(identifier.as_str()))
        .collect()
}

fn typescript_module_path(prefix: &str, path: &Path) -> String {
    let mut path = path.to_path_buf();
    path.set_extension("js");
    format!("{prefix}{}", path.to_string_lossy().replace('\\', "/"))
}

fn normalize_typescript(output: String) -> String {
    let mut normalized = output
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    normalized.push('\n');
    normalized
}

fn binding_output_path(binding: &crate::protocol::registry::TypeScriptBinding) -> PathBuf {
    PathBuf::from(format!("{}.ts", binding.identifier()))
}

fn assert_typescript_bindings_are_closed() {
    let mut registered = BTreeSet::new();
    let mut output_paths = BTreeSet::new();
    for binding in TYPESCRIPT_BINDINGS {
        let identifier = binding.identifier();
        assert!(
            registered.insert(identifier.clone()),
            "duplicate TypeScript binding identifier: {identifier}"
        );
        assert!(
            identifier
                .chars()
                .all(|character| character.is_ascii_alphanumeric() || character == '_'),
            "invalid TypeScript binding identifier: {identifier}"
        );
        let output_path = binding_output_path(binding);
        assert!(
            !output_path.is_absolute()
                && output_path
                    .extension()
                    .is_some_and(|extension| extension == "ts")
                && output_path
                    .components()
                    .all(|component| matches!(component, Component::Normal(_))),
            "invalid TypeScript binding output path: {}",
            output_path.display()
        );
        assert!(
            output_paths.insert(output_path.clone()),
            "duplicate TypeScript binding output path: {}",
            output_path.display()
        );
    }
    let missing = TYPESCRIPT_BINDINGS
        .iter()
        .flat_map(|binding| binding.dependencies())
        .filter(|dependency| !registered.contains(dependency))
        .collect::<BTreeSet<_>>();

    assert!(
        missing.is_empty(),
        "TypeScript bindings are missing declarations for: {}",
        missing.into_iter().collect::<Vec<_>>().join(", ")
    );
}

pub fn json_schema() -> String {
    let schema = protocol_schema_value();
    let mut output =
        serde_json::to_string_pretty(&schema).expect("protocol schema must serialize as JSON");
    output.push('\n');
    output
}

pub(crate) fn protocol_schema_value() -> Value {
    let mut schema =
        serde_json::to_value(protocol_schema()).expect("protocol schema must serialize as JSON");
    canonicalize_json(&mut schema);
    schema
}

fn protocol_schema() -> Schema {
    schema_for!(ProtocolSchema)
}

pub(crate) fn schema_hash() -> String {
    let canonical = serde_json::to_vec(&protocol_schema_value())
        .expect("canonical protocol schema must serialize as JSON");
    let digest = Sha256::digest(canonical);
    format!("sha256:{digest:x}")
}

fn canonicalize_json(value: &mut Value) {
    match value {
        Value::Array(values) => {
            for value in values {
                canonicalize_json(value);
            }
        }
        Value::Object(object) => {
            let mut entries = std::mem::take(object).into_iter().collect::<Vec<_>>();
            for (_, value) in &mut entries {
                canonicalize_json(value);
            }
            entries.sort_by(|left, right| left.0.cmp(&right.0));
            object.extend(entries);
        }
        Value::Null | Value::Bool(_) | Value::Number(_) | Value::String(_) => {}
    }
}

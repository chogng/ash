/** Projects a reply's icon name into the Ash icon registry. */
export function resolveChatGPTIcon(name: string): Icon | undefined {
	const unqualified = name.startsWith('lucide:') ? name.slice('lucide:'.length) : name;
	const normalized = /^[A-Z][A-Za-z0-9]*$/u.test(unqualified)
		? unqualified.replace(/([a-z\d])([A-Z])/gu, '$1-$2').replace(/([A-Z]+)([A-Z][a-z])/gu, '$1-$2')
			.replace(/([A-Za-z])(\d)/gu, '$1-$2').replace(/(\d)x-(\d)/giu, '$1x$2').toLowerCase()
		: unqualified;
	const webName = webIconAliases.get(normalized) ?? normalized;
	const mapped = ashIconsByWebName.get(webName);
	if (mapped) return mapped;
	if (getLxiconDefinition(webName)) return Icon.fromId(webName);
	// Existing replies can also carry a name shared directly with the Ash registry.
	return getLxiconDefinition(normalized) ? Icon.fromId(normalized) : undefined;
}

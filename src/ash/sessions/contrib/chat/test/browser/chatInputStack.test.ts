import { expect } from '@playwright/test';
import { suite, test } from 'mocha';
import { useBrowserTests } from '../../../../../../../test/unit/browser/context.js';
import { QuickAccess } from '../../../../../../../test/automation/quickaccess.js';
import type { } from '../../../github/test/browser/fixtures/sessionGitHub.page.js';

suite('Sessions input stack browser layout', () => {
	const browserTests = useBrowserTests();

	test('PR refresh retains focus and spacing; selecting a draft releases the slot', async () => {
		const { page } = browserTests;
		await page.goto('/sessionGitHub.html?inputStack');
		const prs = page.locator('.ash-session-chat-input-prs');
		const input = page.locator('textarea.ash-chat-input-container');
		const link = prs.locator('.ash-session-chat-input-pr').filter({ hasText: 'one #7' });
		await expect(link).toBeVisible();
		await expect(prs).toHaveCSS('margin-bottom', '0px');
		await expect(input).toHaveCSS('margin-top', '8px');
		await link.focus();
		await page.evaluate(() => window.ashSessionGitHub.setAttention('checks'));
		await expect(link).toHaveAccessibleName(/Checks failed/);
		await expect(link).toBeFocused();
		const upper = await prs.boundingBox();
		const lower = await input.boundingBox();
		expect(lower!.y - upper!.y - upper!.height).toBeCloseTo(8, 0);
		await link.press('Enter');
		await expect.poll(() => page.evaluate(() => window.ashSessionGitHub.opened)).toEqual(['https://github.com/team/one/pull/7']);
		await link.focus();
		await page.evaluate(() => window.ashSessionGitHub.selectDraft());
		await expect(prs).toBeHidden();
		await expect(input).toBeFocused();
		await expect(input).toHaveCSS('margin-top', '0px');
		await expect(input).toHaveValue('Retained PR draft');
		await page.evaluate(() => window.ashSessionGitHub.dispose());
		await expect(prs).toHaveCount(0);
		await expect(input).toHaveCSS('margin-top', '0px');
	});

	test('the real Sessions composer keeps empty PR and onboarding slots out of its layout', async () => {
		const { page } = browserTests;
		await page.goto('/sessions.html?artifacts');
		await expect(page.locator('body')).toHaveAttribute('data-ready', 'true');
		await page.locator('.ash-window-mode-control').getByRole('button', { name: 'Code', exact: true }).click();
		await page.locator('.ash-sessions-activity-content').getByRole('button', { name: /^New(?:\.|$)/u }).click();
		const stack = page.locator('.ash-sessions-chat-slot.active .ash-chat-input-stack');
		await expect(stack).toBeVisible();
		await stack.locator('[data-action-id="ash.chat.input.attach"] button').click();
		const addMenu = page.getByRole('menu', { name: 'Add content or context', exact: true });
		await expect(addMenu.getByRole('menuitem', { name: 'Search attachments' })).toBeVisible();
		await expect(addMenu.getByText('Add to project', { exact: true })).toHaveCount(0);
		await addMenu.getByRole('menuitem', { name: 'Choose project', exact: true }).click();
		const projectSearch = page.getByRole('searchbox', { name: 'Search projects', exact: true });
		await expect(projectSearch).toBeVisible();
		await projectSearch.press('Escape');
		await expect(stack.locator('.ash-session-chat-input-prs')).toBeHidden();
		await expect(stack.locator('.ash-chat-input-notice-slot')).toBeHidden();
		const tip = stack.locator('.ash-chat-input-tip');
		await expect(tip).toBeVisible();
		const input = stack.locator('.ash-chat-input-container');
		const tipBounds = (await tip.boundingBox())!;
		const inputBounds = (await input.boundingBox())!;
		expect(inputBounds.y - tipBounds.y - tipBounds.height).toBeCloseTo(8, 0);
		await expect(input).toHaveCSS('border-top-left-radius', '12px');
		const toolbar = tip.getByRole('toolbar', { name: 'Tip actions' });
		const actions = tip.locator('.ash-chat-input-tip-actions');
		const text = tip.locator('.ash-markdown');
		await page.mouse.move(0, 0);
		await input.getByRole('textbox').focus();
		const textBounds = (await text.boundingBox())!;
		const actionsBounds = (await actions.boundingBox())!;
		expect(textBounds.y + textBounds.height / 2).toBeCloseTo(actionsBounds.y + actionsBounds.height / 2, 0);
		await expect(actions).toHaveCSS('opacity', '0');
		await expect(actions).toHaveCSS('pointer-events', 'none');
		await tip.hover();
		await expect(actions).toHaveCSS('opacity', '1');
		await expect(actions).toHaveCSS('pointer-events', 'auto');
		expect(await text.boundingBox()).toEqual(textBounds);
		expect(await input.boundingBox()).toEqual(inputBounds);
		await page.mouse.move(0, 0);
		await expect(actions).toHaveCSS('opacity', '0');
		await tip.focus();
		await expect(actions).toHaveCSS('opacity', '1');
		const previous = toolbar.getByRole('button', { name: 'Previous tip', exact: true });
		await page.keyboard.press('Tab');
		await expect(previous).toBeFocused();
		const next = toolbar.getByRole('button', { name: 'Next tip', exact: true });
		await next.press('Enter');
		await expect(tip).toContainText('Choose Plan');
		await expect(next).toBeFocused();
		await next.press('ArrowLeft');
		await expect(previous).toBeFocused();
		await previous.press('Enter');
		await expect(tip).toContainText('Attach text files or images');
		await expect(previous).toBeFocused();
		await input.getByRole('textbox').focus();
		await expect(actions).toHaveCSS('opacity', '0');
		await tip.hover();
		await toolbar.getByRole('button', { name: 'Dismiss tip', exact: true }).click();
		await expect(tip).toHaveCount(0);
		await expect(input).toHaveCSS('margin-top', '0px');
		await stack.screenshot({ path: browserTests.info.outputPath('sessions-input-stack.png') });

		const quickAccess = new QuickAccess(page);
		await quickAccess.runCommand('workbench.action.chat.resetDismissedTips');
		await expect(tip).toContainText('Attach text files or images');
		await tip.click({ button: 'right' });
		const dismissCurrent = page.getByRole('menuitem', { name: 'Dismiss This Tip', exact: true });
		const disableAll = page.getByRole('menuitem', { name: 'Disable All Tips', exact: true });
		await expect(disableAll).toBeVisible();
		await dismissCurrent.click();
		await expect(tip).toHaveCount(0);
		await expect(input.getByRole('textbox')).toBeFocused();

		await quickAccess.runCommand('workbench.action.chat.resetDismissedTips');
		await tip.focus();
		await tip.press('Shift+F10');
		await expect(dismissCurrent).toBeFocused();
		await dismissCurrent.press('ArrowDown');
		await expect(disableAll).toBeFocused();
		await disableAll.press('Enter');
		await expect(tip).toHaveCount(0);
		await quickAccess.runCommand('workbench.action.chat.resetDismissedTips');
		await expect(tip).toHaveCount(0);
	});
});

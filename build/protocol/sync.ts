import { mkdir, readFile, readdir, rename, unlink, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

const repositoryRoot = resolve(import.meta.dirname, '../..');
const generatedHeader = '// Generated by `ash-app-server-protocol generate_protocol`. Do not edit.';

/** Materializes the checked-in protocol snapshot without requiring a Rust toolchain. */
export async function syncProtocol(
	sourceDirectory = join(repositoryRoot, 'ash-rs/app-server-protocol/schema/typescript'),
	outputDirectory = join(repositoryRoot, 'ash-ts/src/ash/platform/app-server/common/generated'),
): Promise<void> {
	const sources = await readSources(sourceDirectory);
	for (const entrypoint of ['index.ts', 'protocol.ts', 'AppServerProtocolDecoder.ts', 'WebProtocolDecoder.ts']) {
		if (!sources.has(entrypoint)) throw new Error(`Missing generated protocol entrypoint: ${entrypoint}`);
	}
	await mkdir(outputDirectory, { recursive: true });
	const outputs = await readSources(outputDirectory);
	for (const [name, contents] of sources) {
		if (outputs.get(name) === contents) continue;
		const path = join(outputDirectory, name);
		await mkdir(dirname(path), { recursive: true });
		const temporary = `${path}.${process.pid}.tmp`;
		try {
			await writeFile(temporary, contents);
			await rename(temporary, path);
		} finally {
			await unlink(temporary).catch(error => { if (error.code !== 'ENOENT') throw error; });
		}
	}
	for (const name of outputs.keys()) {
		if (!sources.has(name)) await unlink(join(outputDirectory, name));
	}
}

async function readSources(directory: string, prefix = ''): Promise<Map<string, string>> {
	const files = new Map<string, string>();
	for (const entry of await readdir(join(directory, prefix), { withFileTypes: true })) {
		const name = prefix ? `${prefix}/${entry.name}` : entry.name;
		if (entry.isDirectory()) {
			for (const [path, contents] of await readSources(directory, name)) files.set(path, contents);
		} else if (entry.isFile() && entry.name.endsWith('.ts')) {
			const contents = (await readFile(join(directory, name), 'utf8')).replaceAll('\r\n', '\n');
			if (!contents.startsWith(generatedHeader)) throw new Error(`Unexpected handwritten protocol file: ${join(directory, name)}`);
			files.set(name, contents);
		} else {
			throw new Error(`Unexpected protocol artifact: ${join(directory, name)}`);
		}
	}
	return files;
}

if (import.meta.main) await syncProtocol();

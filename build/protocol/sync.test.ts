import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, readdir, rm, stat, utimes, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { syncProtocol } from './sync.ts';

const header = '// Generated by `ash-app-server-protocol generate_protocol`. Do not edit.\n';
const entrypoints = ['index.ts', 'protocol.ts', 'AppServerProtocolDecoder.ts', 'WebProtocolDecoder.ts'];

test('snapshot synchronization updates changed contracts, removes retired types, and preserves unchanged timestamps', async t => {
	const root = await mkdtemp(join(tmpdir(), 'ash-protocol-'));
	t.after(() => rm(root, { recursive: true, force: true }));
	const source = join(root, 'snapshot');
	const output = join(root, 'frontend');
	await mkdir(join(source, 'types'), { recursive: true });
	for (const name of entrypoints) await writeFile(join(source, name), `${header}export {};\n`);
	await writeFile(join(source, 'types/Retired.ts'), `${header}export type Retired = string;\n`);
	await syncProtocol(source, output);
	const unchanged = join(output, 'index.ts');
	await utimes(unchanged, 1, 1);
	await rm(join(source, 'types/Retired.ts'));
	await writeFile(join(source, 'types/Current.ts'), `${header}export type Current = number;\n`);
	await writeFile(join(source, 'protocol.ts'), `${header}export const version = 2;\n`);
	await syncProtocol(source, output);
	assert.deepEqual(await readdir(join(output, 'types')), ['Current.ts']);
	assert.equal(await readFile(join(output, 'protocol.ts'), 'utf8'), `${header}export const version = 2;\n`);
	assert.equal(await readFile(join(output, 'types/Current.ts'), 'utf8'), await readFile(join(source, 'types/Current.ts'), 'utf8'));
	assert.equal((await stat(unchanged)).mtimeMs, 1000);
});

test('an incomplete snapshot fails without changing the existing frontend contracts', async t => {
	const root = await mkdtemp(join(tmpdir(), 'ash-protocol-'));
	t.after(() => rm(root, { recursive: true, force: true }));
	const source = join(root, 'snapshot');
	const output = join(root, 'frontend');
	await mkdir(source);
	await mkdir(output);
	await writeFile(join(output, 'index.ts'), `${header}export const keep = true;\n`);
	await assert.rejects(syncProtocol(source, output), /Missing generated protocol entrypoint/);
	assert.equal(await readFile(join(output, 'index.ts'), 'utf8'), `${header}export const keep = true;\n`);
});

test('snapshot synchronization rejects handwritten files before overwriting the destination', async t => {
	const root = await mkdtemp(join(tmpdir(), 'ash-protocol-'));
	t.after(() => rm(root, { recursive: true, force: true }));
	const source = join(root, 'snapshot');
	const output = join(root, 'frontend');
	await mkdir(source);
	await mkdir(output);
	for (const name of entrypoints) await writeFile(join(source, name), `${header}export {};\n`);
	await writeFile(join(output, 'index.ts'), 'export const handwritten = true;\n');
	await assert.rejects(syncProtocol(source, output), /Unexpected handwritten protocol file/);
	assert.equal(await readFile(join(output, 'index.ts'), 'utf8'), 'export const handwritten = true;\n');
});

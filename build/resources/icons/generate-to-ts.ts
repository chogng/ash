import type { GeneratedIcon } from "./generate.ts";

export function generateToTs(icons: readonly GeneratedIcon[]): string {
	const factories = icons.map(({ propertyName, svg, fontCharacter }) => `const icon${capitalize(propertyName)} = ${fontCharacter ? `{ fontCharacter: ${JSON.stringify(fontCharacter)}, fallback: () => ${JSON.stringify(svg)} }` : `() => ${JSON.stringify(svg)}`};`);
	const registrations = icons.map(({ id, propertyName }) => `    ${propertyName}: register(${JSON.stringify(id)}, icon${capitalize(propertyName)}),`);
	return [
		"// Generated from resources/icons by build/resources/icons/generate-to-ts.ts.",
		"// Do not edit this file directly.",
		"",
		"import type { IconDefinition as ProductIconDefinition } from './icon.js';",
		"",
		...factories,
		"",
		"export function createProductIconLibrary<T>(register: (id: string, definition: ProductIconDefinition) => T) {",
		"  return {",
		...registrations,
		"  } as const;",
		"}",
		"",
	].join("\n");
}

function capitalize(value: string): string {
	return `${value[0].toUpperCase()}${value.slice(1)}`;
}

import { dirname, relative } from "node:path";

import type { GeneratedIcon } from "./generate.ts";

export function generateToRs(icons: readonly GeneratedIcon[], outputFile: string): string {
	const definitions = icons.map(({ rendering, rustName, sourcePath }) => {
		const includePath = relative(dirname(outputFile), sourcePath).replaceAll("\\", "/");
		return `    pub(crate) const ${rustName}: IconDefinition = IconDefinition::${rendering}(include_bytes!("${includePath}"));`;
	});
	const constants = icons.map(({ id, rustName }) => `    pub const ${rustName}: Icon = Icon::new(IconId::new("${id}"), artwork::${rustName});`);
	const catalog = icons.map(({ rustName }) => `    icons::${rustName},`);
	const artwork = icons.map(({ id, rustName }) => `    ("${id}", artwork::${rustName}),`);
	return [
		"// Generated from resources/icons by build/resources/icons/generate-to-rs.ts.",
		"// Do not edit this file directly.",
		"",
		"use crate::Icon;",
		"use crate::IconDefinition;",
		"use crate::IconId;",
		"",
		"#[rustfmt::skip]",
		"mod artwork {",
		"    use super::IconDefinition;",
		...definitions,
		"}",
		"",
		"#[rustfmt::skip]",
		"pub mod icons {",
		"    use super::Icon;",
		"    use super::IconId;",
		"    use super::artwork;",
		"",
		...constants,
		"}",
		"",
		"#[rustfmt::skip]",
		"pub const ALL_ICONS: &[Icon] = &[",
		...catalog,
		"];",
		"",
		"#[cfg(test)]",
		"#[rustfmt::skip]",
		"pub(crate) const ALL_ARTWORK: &[(&str, IconDefinition)] = &[",
		...artwork,
		"];",
		"",
	].join("\n");
}

"""Build the small Rust host foundation without preparing a business backend package."""

import hashlib
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from build.lib.package_binaries import build_binaries  # noqa: E402
from build.lib.targets import TARGETS, default_target  # noqa: E402


def main() -> None:
    spec = TARGETS[default_target()]
    binaries = build_binaries(
        ROOT,
        spec,
        {"ash-host-logs": None, "ash-host-integrity": None},
        cargo="cargo",
        cargo_profile="dev-small",
        host_build=True,
    )
    executables = {}
    for name, directory in [
        ("ash-host-logs", "host-logs"),
        ("ash-host-integrity", "host-integrity"),
    ]:
        binary = binaries[name]
        contents = binary.read_bytes()
        digest = hashlib.sha256(contents).hexdigest()
        relative = f"{directory}/{digest}/{binary.name}"
        destination = ROOT / ".build/desktop/main" / relative
        destination.parent.parent.mkdir(parents=True, exist_ok=True)
        staging = Path(
            tempfile.mkdtemp(prefix=".staging-", dir=destination.parent.parent)
        )
        try:
            staged_binary = staging / binary.name
            staged_binary.write_bytes(contents)
            shutil.copymode(binary, staged_binary)
            try:
                staging.rename(destination.parent)
            except OSError:
                # Concurrent builds may publish the same digest. Never overwrite a
                # published executable: Windows can still be running that generation.
                if not destination.is_file() or destination.read_bytes() != contents:
                    raise
        finally:
            if staging.exists():
                shutil.rmtree(staging)
        executables[name] = relative
    binding = ROOT / ".build/desktop/hostLogs.ts"
    content = "// Generated by build/desktop/host_logs.py.\n"
    content += f"export const hostLogExecutable = {json.dumps(executables['ash-host-logs'])};\n"
    content += f"export const hostIntegrityExecutable = {json.dumps(executables['ash-host-integrity'])};\n"
    if not binding.exists() or binding.read_text() != content:
        descriptor, temporary = tempfile.mkstemp(dir=binding.parent, suffix=".tmp")
        try:
            with os.fdopen(descriptor, "w", encoding="utf-8") as output:
                output.write(content)
            os.replace(temporary, binding)
        finally:
            Path(temporary).unlink(missing_ok=True)


if __name__ == "__main__":
    main()
